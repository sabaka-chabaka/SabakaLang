using SabakaLang.Engine;

return Cli.Run(args);

internal static class Cli
{
    private const string Usage = """
        SabakaLang

        usage:
          sabaka run   <file.sabaka> [--ext <extension.dll> --ext-dir <plugins/>]...   compile and run a script
          sabaka check <file.sabaka> [--ext <extension.dll> --ext-dir <plugins/>]...   compile only, print diagnostics
          sabaka dump  <file.sabaka> [--ext <extension.dll> --ext-dir <plugins/>]...   print the generated bytecode
          sabaka modules [--ext <extension.dll>]...               list available native modules and their members
        """;

    public static int Run(string[] args)
    {
        if (args.Length == 0 || args[0] is "-h" or "--help") { Console.WriteLine(Usage); return args.Length == 0 ? 1 : 0; }

        var command = args[0];
        string? file = null;
        var extensions = new List<string>();
        var extensionDirs = new List<string>();
        for (var i = 1; i < args.Length; i++)
        {
            if (args[i] is "--ext" or "-e" && i + 1 < args.Length) extensions.Add(args[++i]);
            else if (args[i] is "--ext-dir" && i + 1 < args.Length) extensionDirs.Add(args[++i]);
            else file ??= args[i];
        }

        var engine = new SabakaEngine();

        foreach (var dir in extensionDirs)
        {
            try { engine.Extensions.RegisterDirectory(dir); }
            catch (Exception ex)
            {
                Console.Error.WriteLine($"Cannot load extensions from '{dir}': {ex.Message}");
                return 2;
            }
        }
        foreach (var dll in extensions)
        {
            try { engine.Extensions.RegisterAssemblyFile(dll); }
            catch (Exception ex)
            {
                Console.Error.WriteLine($"Cannot load extension '{dll}': {ex.Message}");
                return 2;
            }
        }

        if (command == "modules") return ListModules(engine);
        if (file is null || !File.Exists(file))
        {
            Console.Error.WriteLine(file is null ? "No script file given." : $"File not found: {file}");
            return 2;
        }

        engine.ModuleSource = new FileModuleSource(Path.GetDirectoryName(Path.GetFullPath(file)));
        var compilation = engine.CompileFile(file);

        foreach (var w in compilation.Warnings) Console.Error.WriteLine($"warning {w}");
        foreach (var e in compilation.Errors) Console.Error.WriteLine($"error {e}");
        if (!compilation.Success) return 1;

        switch (command)
        {
            case "check":
                Console.WriteLine("OK");
                return 0;
            case "dump":
                Console.WriteLine(compilation.Program!.Disassemble());
                return 0;
            case "run":
                var vm = engine.CreateVm(compilation.Program!);
                try
                {
                    vm.Run();
                    return vm.ExitCode;
                }
                catch (SabakaLang.Runtime.RuntimeException ex)
                {
                    Console.Error.WriteLine($"runtime error: {ex.Message}");
                    foreach (var frame in ex.ScriptStack) Console.Error.WriteLine("  " + frame);
                    return 1;
                }
            default:
                Console.Error.WriteLine($"Unknown command '{command}'.\n{Usage}");
                return 2;
        }
    }

    private static int ListModules(SabakaEngine engine)
    {
        foreach (var m in engine.Extensions.Modules.OrderBy(m => m.Name))
        {
            Console.WriteLine($"{m.Name}{(m.AutoImport ? " (auto-imported)" : "")}{(m.Description is null ? "" : " - " + m.Description)}");
            foreach (var f in m.Functions) Console.WriteLine($"  func  {f.Signature}");
            foreach (var c in m.Classes) Console.WriteLine($"  class {c.Name}");
            foreach (var e in m.Extensions) Console.WriteLine($"  ext   {e.Target}.{e.Signature}");
            foreach (var k in m.Constants) Console.WriteLine($"  const {k.Type} {k.Name}");
        }
        return 0;
    }
}
